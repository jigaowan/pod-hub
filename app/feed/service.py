from __future__ import annotations

from email.utils import format_datetime
from xml.etree import ElementTree as ET

from app.common.media import AUDIO_MIME_TYPE, episode_media_filename
from sqlalchemy.orm import Session, sessionmaker

from app.config import Settings
from app.db.repositories import channels as channel_repo
from app.db.repositories import episodes as episode_repo
from app.db.session import get_session_factory
from app.domain.status import TranscriptStatus
from app.feed.schemas import FeedChannel, FeedEpisode
from app.runtime_settings.service import RuntimeSettingsService

PODCAST_NAMESPACE = "https://podcastindex.org/namespace/1.0"
ET.register_namespace("podcast", PODCAST_NAMESPACE)


class FeedService:
    def __init__(
        self,
        settings: Settings,
        *,
        session_factory: sessionmaker[Session] | None = None,
        runtime_settings_service: RuntimeSettingsService | None = None,
    ) -> None:
        self.settings = settings
        self.session_factory = session_factory or get_session_factory(settings)
        self.runtime_settings_service = runtime_settings_service or RuntimeSettingsService(
            settings,
            session_factory=session_factory,
        )

    def render_channel_feed(self, channel_slug: str) -> str | None:
        session = self.session_factory()
        try:
            channel = channel_repo.get_channel_by_slug(session, channel_slug)
            if channel is None:
                return None

            episodes = episode_repo.list_feed_ready_episodes(session, channel.id, channel.source_kind)
            runtime_settings = self.runtime_settings_service.get_effective_settings()
            feed_channel = FeedChannel(
                display_name=channel.display_name,
                source_url=channel.source_url,
                external_channel_id=channel.external_channel_id,
                episodes=[
                    FeedEpisode(
                        id=episode.id,
                        source_video_id=episode.source_video_id,
                        webpage_url=episode.webpage_url,
                        title=episode.title,
                        description=episode.description,
                        published_at=episode.published_at,
                        audio_mime_type=episode.audio_mime_type,
                        audio_bytes=episode.audio_bytes,
                        transcript_ready=(
                            episode.transcript_status == TranscriptStatus.READY and bool(episode.transcript_path)
                        ),
                    )
                    for episode in episodes
                ],
            )
            return self._build_xml(feed_channel, base_url=runtime_settings.base_url)
        finally:
            session.close()

    def _build_xml(self, channel: FeedChannel, *, base_url: str) -> str:
        rss = ET.Element("rss", version="2.0")
        channel_element = ET.SubElement(rss, "channel")

        ET.SubElement(channel_element, "title").text = channel.display_name
        ET.SubElement(channel_element, "link").text = channel.source_url
        ET.SubElement(channel_element, "description").text = (
            f"Podcast feed generated by Pod Hub for {channel.display_name}"
        )
        ET.SubElement(channel_element, "generator").text = "Pod Hub"
        ET.SubElement(channel_element, "language").text = "zh-cn"

        for episode in channel.episodes:
            item = ET.SubElement(channel_element, "item")
            ET.SubElement(item, "title").text = episode.title
            ET.SubElement(item, "description").text = episode.description or ""
            ET.SubElement(item, "guid", {"isPermaLink": "false"}).text = (
                f"podhub:youtube:{channel.external_channel_id}:{episode.source_video_id}"
            )
            ET.SubElement(item, "link").text = episode.webpage_url
            if episode.published_at is not None:
                ET.SubElement(item, "pubDate").text = format_datetime(episode.published_at)
            ET.SubElement(
                item,
                "enclosure",
                {
                    "url": f"{base_url}/media/{episode_media_filename(episode.id)}",
                    "length": str(episode.audio_bytes or 0),
                    "type": episode.audio_mime_type or AUDIO_MIME_TYPE,
                },
            )
            if episode.transcript_ready:
                ET.SubElement(
                    item,
                    f"{{{PODCAST_NAMESPACE}}}transcript",
                    {
                        "url": f"{base_url}/transcripts/{episode.id}.vtt",
                        "type": "text/vtt",
                        "rel": "captions",
                    },
                )

        return ET.tostring(rss, encoding="utf-8", xml_declaration=True).decode("utf-8")
